    public void tampilData() {
        String[] judulKolom = {"ID Usaha", "Nama Usaha", "Alamat Usaha", "Email"};
        Object[][] dataTabel = new Object[listPelaku.size()][4];
        
        for (int i = 0; i < listPelaku.size(); i++) {
            dataTabel[i][0] = listPelaku.get(i).getIdUsaha();      
            dataTabel[i][1] = listPelaku.get(i).getNamaUsaha();     
            dataTabel[i][2] = listPelaku.get(i).getAlamatUsaha();     
            dataTabel[i][3] = listPelaku.get(i).getEmail();    
        }
        
        tblPelaku.setModel(new javax.swing.table.DefaultTableModel(dataTabel, judulKolom));
    }

