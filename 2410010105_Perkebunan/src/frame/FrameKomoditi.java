    private void tampilData() {
   String[] judulKolom = {"ID", "Nama", "Produsen", "Harga", "Kualitas", "Total"};
        Object[][] dataTabel = new Object[listKomoditi.size()][6];
        
        for (int i = 0; i < listKomoditi.size(); i++) {
            Komoditi k = listKomoditi.get(i);
            dataTabel[i][0] = k.getKualitas().isEmpty() ? "" : k.getKualitas().substring(0,1);
            dataTabel[i][1] = k.listDataNama().isEmpty() ? "" : k.listDataNama().get(i);    
            dataTabel[i][2] = "Perkebunan";    
            dataTabel[i][3] = k.getHarga();    
            dataTabel[i][4] = k.getKualitas();    
            dataTabel[i][5] = k.hargaAkhir();    
        }
        tblKomoditi.setModel(new javax.swing.table.DefaultTableModel(dataTabel, judulKolom));     
    }

    private void bersihkanForm() {
       txtIdKomoditi.setText("");
        txtNamaKomoditi.setText("");
        txtProdusen.setText("");
        txtHarga.setText("");
        txtIdKomoditi.requestFocus();
    }
