    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed

    // Mengambil teks dari form inputan
    String id = txtIdUsaha.getText();
    String nama = txtNamaUsaha.getText();
    String alamat = txtAlamatUsaha.getText();
    String email = txtEmail.getText();

    // Menggunakan method inputData bawaan class Pelaku milikmu
    Pelaku pelakuBaru = new Pelaku();
    pelakuBaru.inputDataId(id);
    pelakuBaru.inputDataNama(nama);
    pelakuBaru.inputDataAlamat(alamat);
    pelakuBaru.inputDataEmail(email);

    // Memasukkan objek pelaku ke dalam listPelaku Frame
    listPelaku.add(pelakuBaru);

    // Memperbarui tampilan tabel dan mengosongkan form kembali
    tampilData();
    bersihkanForm();
    // Munculkan notifikasi sukses
    javax.swing.JOptionPane.showMessageDialog(this, "Data Pelaku Berhasil Disimpan!");        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
String id = txtIdUsaha.getText();
    String nama = txtNamaUsaha.getText();
    String alamat = txtAlamatUsaha.getText();
    String email = txtEmail.getText();

    if (!listPelaku.isEmpty()) {
        Pelaku p = listPelaku.get(0);
        // Menggunakan method ubahDataPelaku bawaan class Pelaku milikmu
        p.ubahDataPelaku(id, nama, alamat, email);
        
        tampilData();
        bersihkanForm();
        javax.swing.JOptionPane.showMessageDialog(this, "Data Pelaku Berhasil Diubah!");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Belum ada data untuk diedit!");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
String id = txtIdUsaha.getText();

    if (!listPelaku.isEmpty()) {
        Pelaku p = listPelaku.get(0);
        // Menggunakan method hapusDataPelaku bawaan class Pelaku milikmu
        p.hapusDataPelaku(id);
        
        tampilData();
        bersihkanForm();
        javax.swing.JOptionPane.showMessageDialog(this, "Data Pelaku Berhasil Dihapus!");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Belum ada data untuk dihapus!");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

